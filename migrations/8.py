"""The low LOD textures and the bridge models made by the old converters become flags: generated when exporting.

The converters wrote the files in the city folder and set their paths on the elements; now the flags generateLodTexture
(roads) and generateMesh (bridges) make them in the export folder, and the editor shows the models from its cache.
The generated files no longer used are moved to generated.v7.bak in the city folder (never deleted, and not packed in
the AR files, which take only the geometry and texture folders of the city).
"""
import copy
import os
import re
import shutil
import sys
import MigrationHelper

LOD_TEXTURE = re.compile(r'texture/[a-z0-9_]+_lod_[0-9a-f]{6}\.tex')
LOD_FILE = re.compile(r'[a-z0-9_]+_lod_[0-9a-f]{6}(_fa)?\.tex')
BRIDGE_MODEL = re.compile(r'geometry/bridge_[0-9a-f]{8}\.pkg')
BRIDGE_NAME = re.compile(r'bridge_[0-9a-f]{8}')
BACKUP = 'generated.v7.bak'


def normalized(path):
    return path.replace('\\', '/').lower() if isinstance(path, str) else ''


def migrate_road_state(state, folder):
    if not isinstance(state, dict):
        return
    path = normalized(state.get('textureLOD'))
    if LOD_TEXTURE.fullmatch(path) and os.path.isfile(os.path.join(folder, *path.split('/'))):
        state['generateLodTexture'] = True
        state['textureLOD'] = ''


def migrate_bridge_state(state):
    if not isinstance(state, dict):
        return
    mesh, generated = state.get('mesh'), state.pop('generatedMesh', None)
    state.pop('generatedLength', None)
    if isinstance(mesh, str) and mesh and mesh == generated:
        state['generateMesh'] = True
        state['mesh'] = ''


def migrate_city(source, folder):
    data = copy.deepcopy(source)
    for road in data.get('roads') or []:
        migrate_road_state(road.get('state'), folder)
    for key in ('customElements', 'lowLevelElements'):
        for element in data.get(key) or []:
            state = element.get('state')
            if isinstance(state, dict) and state.get('type') == 'bridge':
                migrate_bridge_state(state)
    return data


def migrate_presets(source, folder):
    data = copy.deepcopy(source)
    presets = data.get('presets') if isinstance(data, dict) else None
    if not isinstance(presets, dict):
        return data
    for state in presets.get('road') or []:
        migrate_road_state(state, folder)
    for category in ('customElement/bridge', 'lowLevel/bridge'):
        for state in presets.get(category) or []:
            migrate_bridge_state(state)
    return data


def strings(value, res):
    # every string in the data (the paths still used, wherever they are)
    if isinstance(value, dict):
        for v in value.values():
            strings(v, res)
    elif isinstance(value, list):
        for v in value:
            strings(v, res)
    elif isinstance(value, str):
        res.add(normalized(value))
    return res


def unused_files(folder, used):
    """The files made by the old converters that the city no longer uses, relative to its folder."""
    res = []
    texture = os.path.join(folder, 'texture')
    for name in sorted(os.listdir(texture)) if os.path.isdir(texture) else []:
        if LOD_FILE.fullmatch(name.lower()):
            # a _fa variant goes with its texture
            main = 'texture/' + re.sub(r'_fa\.tex$', '.tex', name.lower())
            if main not in used:
                res.append('texture/' + name)
    geometry = os.path.join(folder, 'geometry')
    for name in sorted(os.listdir(geometry)) if os.path.isdir(geometry) else []:
        stem, extension = os.path.splitext(name)
        if extension.lower() != '.pkg' or not BRIDGE_NAME.fullmatch(stem.lower()) or 'geometry/' + name.lower() in used:
            continue
        res.append('geometry/' + name)
        for subfolder, file_name in (('bound', stem + '_BOUND.bnd'), ('tune/banger', stem + '.dgBangerData')):
            path = os.path.join(folder, *subfolder.split('/'))
            match = next((e for e in os.listdir(path) if e.lower() == file_name.lower()), None) if os.path.isdir(path) else None
            if match:
                res.append(subfolder + '/' + match)
    return res


def move_to_backup(folder, files):
    for relative in files:
        target = os.path.join(folder, BACKUP, *relative.split('/'))
        os.makedirs(os.path.dirname(target), exist_ok=True)
        shutil.move(os.path.join(folder, *relative.split('/')), target)
    if files:
        print(str(len(files)) + ' files generated by older versions were moved to ' + BACKUP)


def process_folder(helper):
    if helper.get_pref('coreVersion', 0) >= 8:
        return
    folder = helper.path
    old_presets = helper.read_local('presets.json', False) if os.path.isfile(helper.path + 'presets.json') else None
    presets = migrate_presets(old_presets, folder) if old_presets is not None else None
    city = migrate_city(helper.read_local('city.json.gz', True), folder)
    used = strings(city, set()) | strings(presets, set())
    files = unused_files(folder, used)
    # Validate the complete conversion before backing up or writing any file. Publish the version last.
    helper.read_and_backup('city.json.gz', True)
    preferences = helper.read_and_backup('preferences.json', False)
    if presets is not None and presets != old_presets:
        helper.read_and_backup('presets.json', False)
        helper.save(presets, 'presets.json', False)
    helper.save(city, 'city.json.gz', True)
    move_to_backup(folder, files)
    preferences['coreVersion'] = 8
    helper.save(preferences, 'preferences.json', False)


if __name__ == '__main__' or 'mh' in globals():
    process_folder(MigrationHelper.MigrationHelper(sys.argv[1]))
    print('done 8')
